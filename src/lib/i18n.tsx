export type TranslationKey = keyof (typeof translations)['en']

type I18nContextValue = {
  locale: Locale
  setLocale: (locale: Locale) => void
  t: (key: TranslationKey) => string
}

const I18nContext = createContext<I18nContextValue | null>(null)

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>('en')

  useEffect(() => {
    const saved = window.localStorage.getItem('sharedspace-locale')
    if (saved === 'en' || saved === 'no') {
      setLocaleState(saved)
      document.documentElement.lang = saved === 'no' ? 'nb' : 'en'
    }
  }, [])

  const setLocale = (next: Locale) => {
    window.localStorage.setItem('sharedspace-locale', next)
    document.documentElement.lang = next === 'no' ? 'nb' : 'en'
    setLocaleState(next)
  }

  return (
    <I18nContext.Provider
      value={{ locale, setLocale, t: (key) => translations[locale][key] }}
    >
      {children}
    </I18nContext.Provider>
  )
}

export function useI18n() {
  const context = useContext(I18nContext)
  if (!context) throw new Error('useI18n must be used within I18nProvider')
  return context
}
